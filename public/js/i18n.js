function currentLang() {
  if (typeof state !== 'undefined' && state.lang) return state.lang === 'en' ? 'en' : 'ar';
  return localStorage.getItem('nova.lang') === 'en' ? 'en' : 'ar';
}

function t(key, vars = null) {
  const lang = currentLang();
  const dict = I18N[lang] || I18N.ar;
  let str = dict[key] !== undefined ? dict[key] : (I18N.ar[key] !== undefined ? I18N.ar[key] : key);
  if (vars && typeof str === 'string') {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (typeof val === 'string') el.textContent = val;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (typeof val === 'string') el.setAttribute('placeholder', val);
  });

  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (typeof val === 'string') el.setAttribute('title', val);
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    const val = t(key);
    if (typeof val === 'string') el.setAttribute('aria-label', val);
  });
}

function applyLanguage(lang, { notify = false } = {}) {
  const next = lang === 'en' ? 'en' : 'ar';
  if (typeof state !== 'undefined') state.lang = next;
  localStorage.setItem('nova.lang', next);

  document.documentElement.lang = next;
  document.documentElement.dir = next === 'en' ? 'ltr' : 'rtl';

  const langBtnLabel = document.getElementById('lang-btn-label');
  if (langBtnLabel) langBtnLabel.textContent = t('langShort');

  applyStaticTranslations();

  if (typeof renderSessions === 'function') renderSessions();
  if (typeof updateHeader === 'function') updateHeader();
  if (typeof updateModeUI === 'function') updateModeUI();
  if (typeof updateModelUI === 'function') updateModelUI();
  if (typeof updateConnectionUI === 'function') updateConnectionUI();
  if (typeof updateSendButton === 'function') updateSendButton();
  if (typeof updateWorkspaceUI === 'function') updateWorkspaceUI();
  if (typeof updateProviderHint === 'function') updateProviderHint();
  if (typeof updateSettingsSummary === 'function') updateSettingsSummary();
  if (typeof updateMobileSummaryUI === 'function') updateMobileSummaryUI(null);
  if (typeof renderBuiltPackages === 'function') renderBuiltPackages();

  const statusEl = document.getElementById('agent-status');
  if (statusEl && typeof state !== 'undefined' && !state.streaming) {
    if (state.pending) {
      statusEl.textContent = state.pending.kind === 'approval' ? t('awaitingApproval') : t('awaitingReply');
    } else {
      statusEl.textContent = t('ready');
    }
  }

  if (typeof state !== 'undefined') {
    if (!state.session) {
      if (typeof renderWelcome === 'function') renderWelcome();
    } else if (Array.isArray(state.session.transcript) && typeof renderTranscript === 'function') {
      renderTranscript(state.session.transcript, state.pending);
    }
  }

  const wsPanel = document.getElementById('workspace-panel');
  if (wsPanel && !wsPanel.hidden && typeof loadWorkspaceFiles === 'function') {
    loadWorkspaceFiles(typeof workspacePath !== 'undefined' ? workspacePath : '');
  }

  const cmdBackdrop = document.getElementById('command-backdrop');
  if (cmdBackdrop && !cmdBackdrop.hidden && typeof renderCommands === 'function') {
    renderCommands();
  }

  if (notify && typeof toast === 'function') {
    toast(t('langSwitched'), 'info', 2200);
  }
}
